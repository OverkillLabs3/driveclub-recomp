// Start-up scripts of mods. The game runs scripts/bootscripts/defaultbootscript.lua.bin or releasebootscript.lua.bin
// once at start (the names are in the game's executable). Both are replaced by a short Lua text that runs the original
// script, kept next to it under another name, and then the Lua files that mods list under "scripts".
#include "lua.hpp"
#include "mod.hpp"

namespace dcmod {

std::string BootWrapper(const std::string& original, const std::vector<std::string>& scripts) {
    // The Lua text is loaded by the game's own boot script loader, which accepts text; the mod scripts are bytecode.
    std::string lua = R"LUA(-- Generated by dcmod: runs the game's own boot script, then the scripts of the mods.
local original = assert(loadfile(")LUA" + original + R"LUA("))
original()
local dcmod = { version = 1 }
-- dcmod.log(...) writes a line to the game log, starting with "Mod: ". The log call is a failed loadfile of a path
-- that the runtime recognises; capital letters are sent as ^ and the letter because the game lower-cases paths.
function dcmod.log(...)
  local parts = {}
  for i = 1, select("#", ...) do parts[#parts + 1] = tostring((select(i, ...))) end
  local text = string.sub(table.concat(parts, " "), 1, 380)
  text = string.gsub(text, "[^%w%s%.:=_,%-%(%)%[%]]", "?")
  text = string.gsub(text, "%u", function(c) return "^" .. string.lower(c) end)
  loadfile("dcmod/log/" .. text)
end
rawset(_G, "dcmod", dcmod)
local function run(path)
  local chunk, err = loadfile(path)
  if not chunk then
    dcmod.log("cannot load", path, err)
    return
  end
  local ok, problem = pcall(chunk)
  if not ok then dcmod.log("error in", path, problem) end
end
)LUA";
    for (const std::string& s : scripts) lua += "run(\"" + s + "\")\n";
    return lua;
}

void AddScriptLoader(Workspace& ws, const std::vector<Mod>& ordered) {
    std::vector<std::string> scripts;
    for (const Mod& m : ordered) scripts.insert(scripts.end(), m.scripts.begin(), m.scripts.end());
    if (scripts.empty()) return;
    // The game cannot run chunks it compiles from text itself, but it runs bytecode: source scripts are compiled here.
    std::vector<std::string> loadable;
    for (const std::string& s : scripts) {
        if (s.find_first_of("\"\\\n") != std::string::npos) {
            throw Error("the script name \"" + s + "\" has characters that are not allowed");
        }
        if (!ws.Exists(s)) throw Error("the script " + s + " is listed under \"scripts\" but no mod provides it");
        const Bytes data = ws.Read(s);
        if (IsLuaBytecode(data)) {
            loadable.push_back(s);
            continue;
        }
        Bytes compiled;
        try {
            compiled = CompileLua(std::string(data.begin(), data.end()), s);
        } catch (const Error& e) {
            throw Error("the script " + s + " does not compile: " + e.what());
        }
        ws.Write(s + ".bin", compiled, "dcmod", "compiled script");
        loadable.push_back(s + ".bin");
    }
    scripts = loadable;
    for (const char* name : {"defaultbootscript", "releasebootscript"}) {
        const std::string path = std::string("scripts/bootscripts/") + name + ".lua.bin";
        const std::string original = std::string("scripts/bootscripts/") + name + "_dcmod_original.lua.bin";
        ws.Write(original, ws.Read(path), "dcmod", "boot script copy");
        const std::string lua = BootWrapper(original, scripts);
        ws.Write(path, Bytes(lua.begin(), lua.end()), "dcmod", "boot script wrapper");
    }
}

}  // namespace dcmod
