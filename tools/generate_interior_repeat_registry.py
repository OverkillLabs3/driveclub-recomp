#!/usr/bin/env python3
"""Generate narrow opaque-interior material ownership metadata from native RPKs.

Supply legally owned global.rpk and vehicleglobal.rpk. The material cohort is a
semantic proxy for plain upholstery/panel grain, not a geometry/flatness test.
Only program hashes are emitted; runtime UV, format and normal-role gates apply.
"""
import argparse
import hashlib
from pathlib import Path

from generate_world_repeat_registry import classify as classify_owners, resources


# Source provenance, not display names or texture IDs. Shared programs are
# accepted only when every owner and every owner source belongs to this cohort.
# leather_glow shares grain programs with leather; emission is never selected.
INTERIOR_SOURCES = frozenset(
    "assets/noodle/materials/vehicle/" + family + ".material"
    for family in ("leather", "leather_glow", "leather_stitched",
                   "fuzzy_felt", "fuzzy_felt_stitched")
)


def is_interior_grain_source(source):
    return source in INTERIOR_SOURCES


def classify(entries):
    return classify_owners(entries, source_eligible=is_interior_grain_source)


def render(programs):
    lines = ["// Generated by tools/generate_interior_repeat_registry.py; do not edit by hand.",
             "// All-owner plain upholstery cohort; runtime normal/UV gates still apply.",
             "// No texture IDs, shader instructions or geometry/flatness guarantee."]
    for start in range(0, len(programs), 6):
        lines.append(" ".join(f"0x{value:016x}ull," for value in programs[start:start + 6]))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("packages", type=Path, nargs="+")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] /
                        "gpu/shadps4/shader_recompiler/backend/spirv/interior_repeat_programs.inc")
    args = parser.parse_args()
    entries = []
    for path in args.packages:
        blob = path.read_bytes()
        print(path.name, hashlib.sha256(blob).hexdigest())
        entries.extend(resources(blob))
    programs = classify(entries)
    args.output.write_text(render(programs), encoding="utf-8", newline="\n")
    print(f"Wrote {len(programs)} interior-owned pixel programs to {args.output}")


if __name__ == "__main__":
    main()
