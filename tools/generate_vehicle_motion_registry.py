#!/usr/bin/env python3
"""Generate positive vehicle-program provenance from native RPKs.

All sources of every known owner must belong to the native vehicle material
family. Shared/unknown programs retain the old renderer admission path.
"""
import argparse
import hashlib
from pathlib import Path
import re
import struct

class Reader:

    def __init__(self, data, offset=0):
        self.data, self.offset = (data, offset)

    def read(self, fmt):
        result = struct.unpack_from('<' + fmt, self.data, self.offset)
        self.offset += struct.calcsize('<' + fmt)
        return result[0] if len(result) == 1 else result

    def take(self, size):
        start = self.offset
        self.offset += size
        if self.offset > len(self.data):
            raise ValueError('Truncated RPK')
        return self.data[start:self.offset]

    def header(self):
        if self.take(8) != b'EVOSLITL':
            raise ValueError('Unexpected RPK header')

    def string(self):
        return self.take(self.read('I')).decode('utf-8')

def resources(data):
    reader = Reader(data)
    reader.header()
    if reader.string() != 'Resource PacK file':
        raise ValueError('Not an RPK resource package')
    _, index = reader.read('II')
    reader.offset = index
    reader.header()
    uid, version = reader.read('QI')
    if uid >> 48 != 1 or reader.read('I') != 286331153:
        raise ValueError('Unexpected RPK index')
    count, _, _, name_size, source_size = reader.read('IIIII')
    if version >= 262146:
        reader.read('II')
    reader.read('Q')
    names, sources = (reader.take(name_size), reader.take(source_size))

    def strings(pool):
        result = []
        for _ in range(reader.read('H')):
            offset = reader.read('I')
            result.append(pool[offset:pool.index(0, offset)].decode('utf-8'))
        return result
    result = []
    for _ in range(count):
        uid, size, offset = reader.read('QII')
        deps = [reader.read('Q') for _ in range(reader.read('H'))]
        result.append(dict(uid=uid, size=size, offset=offset, dependencies=deps, names=strings(names), sources=strings(sources), package=data))
    return result

def pixel_program_owners(entries):
    """Collect all owners before filtering, including unknown provenance.

    Different shader resource IDs can contain the same native program.
    """
    by_id = {entry['uid']: entry for entry in entries}
    owners = {}
    for material in entries:
        if material['uid'] >> 48 != 6:
            continue
        programs = set()
        for dep in set(material['dependencies']):
            shader = by_id.get(dep)
            if not shader or shader['uid'] >> 48 != 29 or shader['names'] != ['PixelShader']:
                continue
            blob = shader['package'][shader['offset']:shader['offset'] + shader['size']]
            for marker in re.finditer(b'OrbShdr', blob):
                if marker.start() + 24 > len(blob):
                    raise ValueError('Truncated shader metadata')
                program = struct.unpack_from('<Q', blob, marker.start() + 16)[0]
                programs.add(program)
        for program in programs:
            owners.setdefault(program, []).append(material)
    return owners

def classify_owners(entries, source_eligible):
    return sorted(
        program
        for program, owners in pixel_program_owners(entries).items()
        if all(
            owner['sources'] and all(source_eligible(source) for source in owner['sources'])
            for owner in owners
        )
    )


ROOT = 'assets/noodle/materials/vehicle/'


def vehicle_source(source):
    if not source.startswith(ROOT):
        return False
    family = source[len(ROOT):]
    return bool(family and family.endswith('.material') and '/' not in family and '\\' not in family)


def classify(entries):
    return classify_owners(entries, source_eligible=vehicle_source)


def render(programs):
    lines = [
        '// Generated by generate_vehicle_motion_registry.py; no texture IDs or shader instructions.',
        '// Every source of every known native pixel-program owner is a vehicle material family.',
    ]
    for i in range(0, len(programs), 6):
        lines.append(' '.join(f'0x{x:016x}ull,' for x in programs[i:i + 6]))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('packages', type=Path, nargs='+')
    parser.add_argument(
        '--output',
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / 'gpu/shadps4/video_core/renderer_vulkan/vehicle_motion_programs.inc',
    )
    args = parser.parse_args()
    entries = []
    for path in args.packages:
        blob = path.read_bytes()
        print(path.name, hashlib.sha256(blob).hexdigest())
        entries += resources(blob)
    programs = classify(entries)
    args.output.write_text(render(programs), encoding='utf-8', newline='\n')
    print('vehicle programs', len(programs))


if __name__ == '__main__':
    main()
